"""Engine event dataclasses for the bus and simulation pipeline.

All events are frozen dataclasses with slots and timezone-aware UTC timestamps.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

from algodesk.api.market import (
    Bar,
    FeedStatus,
    InstrumentId,
    MarketEvent,
    Quote,
    Tick,
    _validate_utc_ts,
)
from algodesk.api.trading import Fill, Intent, Order, OrderEvent, Portfolio, RiskDecision

__all__ = [
    "BarClosed",
    "FeedStatus",
    "FillEvent",
    "IntentEvent",
    "MarketEvent",
    "OrderEventMsg",
    "PortfolioEvent",
    "Quote",
    "RiskEvent",
    "Signal",
    "SystemEvent",
    "Tick",
    "TimerEvent",
]


@dataclass(frozen=True, slots=True)
class BarClosed:
    """Published when a bar period completes."""

    bar: Bar

    @property
    def instrument(self) -> InstrumentId:
        return self.bar.instrument

    @property
    def ts(self) -> datetime:
        return self.bar.end_ts


@dataclass(frozen=True, slots=True)
class Signal:
    """Generated by a strategy on bar or tick evaluation."""

    strategy_id: str
    instrument: InstrumentId
    signal_type: str
    ts: datetime
    metrics: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        _validate_utc_ts(self.ts, "ts")
        if not self.strategy_id:
            raise ValueError("strategy_id cannot be empty")
        if not self.signal_type:
            raise ValueError("signal_type cannot be empty")


@dataclass(frozen=True, slots=True)
class IntentEvent:
    """Trading intent issued by strategy runtime."""

    intent: Intent
    ts: datetime

    def __post_init__(self) -> None:
        _validate_utc_ts(self.ts, "ts")


@dataclass(frozen=True, slots=True)
class RiskEvent:
    """Evaluated risk decision for an intent."""

    decision: RiskDecision
    intent: Intent
    ts: datetime

    def __post_init__(self) -> None:
        _validate_utc_ts(self.ts, "ts")


@dataclass(frozen=True, slots=True)
class OrderEventMsg:
    """Lifecycle transition event for an order."""

    event: OrderEvent
    order: Order | None = None

    @property
    def ts(self) -> datetime:
        return self.event.ts


@dataclass(frozen=True, slots=True)
class FillEvent:
    """Execution fill event reported by venue."""

    fill: Fill
    order: Order | None = None

    @property
    def ts(self) -> datetime:
        return self.fill.ts


@dataclass(frozen=True, slots=True)
class PortfolioEvent:
    """Periodic or fill-driven portfolio state snapshot."""

    portfolio: Portfolio
    ts: datetime

    def __post_init__(self) -> None:
        _validate_utc_ts(self.ts, "ts")


@dataclass(frozen=True, slots=True)
class TimerEvent:
    """Scheduled timer trigger event."""

    name: str
    ts: datetime

    def __post_init__(self) -> None:
        _validate_utc_ts(self.ts, "ts")
        if not self.name:
            raise ValueError("Timer name cannot be empty")


@dataclass(frozen=True, slots=True)
class SystemEvent:
    """Engine and runtime operational message."""

    kind: str
    message: str
    ts: datetime
    details: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        _validate_utc_ts(self.ts, "ts")
        if not self.kind:
            raise ValueError("SystemEvent kind cannot be empty")
